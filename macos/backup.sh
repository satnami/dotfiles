#!/usr/bin/env bash

# Read the macOS preferences listed in macos/keys.list off this machine and
# regenerate macos/non-defaults.sh from them, the way Brew/backup.sh regenerates
# the Brewfile. Works from any directory. Keys that are not set are skipped and
# reported, so the output only ever holds settings that exist here.
#
# Add a key to keys.list to start tracking it; run this after changing something
# in System Settings to capture it.

set -u

DIR="$(cd "$(dirname "$0")" && pwd)"
LIST="$DIR/keys.list"
OUT="$DIR/non-defaults.sh"
TMP="$OUT.tmp.$$"

trap 'rm -f "$TMP"' EXIT

[ -f "$LIST" ] || { echo "no key list at $LIST" >&2; exit 1; }

# Keys holding dots or spaces get quoted so the generated file stays copy-pasteable.
quote_key() {
  case "$1" in
    *.*|*" "*) printf '"%s"' "$1" ;;
    *)         printf '%s' "$1" ;;
  esac
}

# emit_write <scope> <domain> <key>
# Prints one `defaults write ...` line, or returns 1 when the key is unset or
# not a scalar. <scope> is "" or "-currentHost" and must stay unquoted in the
# `defaults` calls, where an empty string would become a bogus argument.
emit_write() {
  local scope="$1" domain="$2" key="$3" type value flag

  # shellcheck disable=SC2086
  type="$(defaults $scope read-type "$domain" "$key" 2>/dev/null)" || return 1
  # shellcheck disable=SC2086
  value="$(defaults $scope read "$domain" "$key" 2>/dev/null)" || return 1

  case "$type" in
    "Type is boolean")
      flag="-bool"
      if [ "$value" = "1" ]; then value="true"; else value="false"; fi ;;
    "Type is integer") flag="-int" ;;
    "Type is float")   flag="-float" ;;
    "Type is string")  flag="-string"; value="\"$value\"" ;;
    *)
      # Dictionaries, arrays and raw data need a plist literal, not a scalar.
      printf '    skip  %s%s %s (%s)\n' "${scope:+$scope }" "$domain" "$key" "$type" >&2
      return 2 ;;
  esac

  printf 'defaults %swrite %s %s %s %s\n' "${scope:+$scope }" "$domain" "$(quote_key "$key")" "$flag" "$value"
}

{
  cat <<HEADER
#!/bin/sh

# Backup of the macOS preferences that differ from Apple's defaults on this
# machine, captured on $(date +%Y-%m-%d). Companion to macos/setup.sh: that file
# holds the opinionated set we want on every machine, this one restores the
# choices already made by hand in System Settings.
#
# Generated by macos/backup.sh from macos/keys.list. Edit those, not this file:
# the next backup run overwrites everything below.
#
# Run as your own user, never with sudo. Idempotent; setup.sh runs it.
#
# Trackpad and keyboard keys here are read by the window server at login, so
# those changes land after the next logout, not immediately.
HEADER

  # Everything before the first `## ` section is this file's own documentation
  # and stays out of the output; comments after one are kept.
  in_body=""

  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      '## '*)
        in_body=1
        title="${line#\#\# }"
        # 74-column rule, like the hand-written sections in macos/setup.sh.
        rule="$(printf '%*s' "$((72 - ${#title}))" '' | tr ' ' '-')"
        printf '\n# %s %s\n' "$rule" "$title" ;;
      '')
        : ;;                                # section headers bring their own blank line
      '#'*)
        [ -n "$in_body" ] && printf '%s\n' "$line" ;;
      *)
        spec="${line%%|*}"
        if [ "$spec" = "$line" ]; then comment=""; else comment="${line#*|}"; fi
        # shellcheck disable=SC2086
        set -- $spec
        if [ "$1" = "-currentHost" ]; then scope="-currentHost"; shift; else scope=""; fi
        out="$(emit_write "$scope" "$1" "$2")"
        case $? in
          0) : ;;
          2) continue ;;                    # emit_write already reported why
          *) printf '    skip  %s%s %s (not set)\n' "${scope:+$scope }" "$1" "$2" >&2
             continue ;;
        esac
        [ -n "$comment" ] && printf '#%s\n' "$comment"
        printf '%s\n' "$out" ;;
    esac
  done < "$LIST"

  cat <<'FOOTER'

# ------------------------------------------------------------------- Restart
# None here: setup.sh runs this file before macos/setup.sh, which restarts
# Finder, Dock and SystemUIServer once at the end. Running this file on its own
# needs that by hand: killall Finder Dock SystemUIServer

printf '    ok    macOS non-default prefs written\n'
FOOTER
} > "$TMP"

chmod +x "$TMP"
mv "$TMP" "$OUT"
echo "wrote $OUT"
